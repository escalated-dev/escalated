#!/usr/bin/env node
/**
 * Write the list of page names this package can resolve.
 *
 * Generated from `src/pages/**` rather than maintained by hand, so it cannot
 * describe a component that is not there or miss one that is. The backends
 * render page names as plain strings, and a name with nothing behind it is not
 * an error in Inertia -- it resolves to nothing and the panel comes up blank.
 * This file is what lets each backend check its own names in CI, which is the
 * only place both halves of that comparison are known.
 */
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pagesDir = join(root, 'src', 'pages');
const output = join(root, 'pages.json');

function walk(dir) {
    return readdirSync(dir).flatMap((entry) => {
        const path = join(dir, entry);
        return statSync(path).isDirectory() ? walk(path) : [path];
    });
}

const pages = walk(pagesDir)
    .filter((path) => path.endsWith('.vue'))
    .map((path) => `Escalated/${relative(pagesDir, path).slice(0, -4).split(sep).join('/')}`)
    .sort();

const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const manifest = {
    $comment:
        'Generated by scripts/generate-page-manifest.js from src/pages. Every name here resolves to a component; a name a backend renders that is not here is a blank screen.',
    version,
    pages,
};

const serialised = `${JSON.stringify(manifest, null, 4)}\n`;
const existing = (() => {
    try {
        return readFileSync(output, 'utf8');
    } catch {
        return null;
    }
})();

// --check is how CI asks whether the committed file still matches the pages on
// disk, without writing anything.
if (process.argv.includes('--check')) {
    if (existing !== serialised) {
        console.error('pages.json is out of date. Run: npm run pages:manifest');
        process.exit(1);
    }

    console.log(`pages.json is current (${pages.length} pages)`);
    process.exit(0);
}

writeFileSync(output, serialised);
console.log(`wrote pages.json (${pages.length} pages)`);
