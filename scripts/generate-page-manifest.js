#!/usr/bin/env node
/**
 * Write the list of page names this package can resolve, and the props each one
 * reads.
 *
 * Generated from `src/pages/**` rather than maintained by hand, so it cannot
 * describe a component that is not there or miss one that is.
 *
 * The backends render page names as plain strings, and a name with nothing
 * behind it is not an error in Inertia -- it resolves to nothing and the panel
 * comes up blank. The names are what lets each backend check that in CI, which
 * is the only place both halves of that comparison are known.
 *
 * The props are the same problem one level down. A name that resolves is not a
 * screen that works: a backend that sends `data` to a component reading
 * `period_days` renders the chrome and no content, on a 200, and an empty
 * report reads as a quiet week rather than a wiring fault. So each page also
 * publishes the props it declares, and which of those it cannot do without.
 */
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse, compileScript } from 'vue/compiler-sfc';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pagesDir = join(root, 'src', 'pages');
const output = join(root, 'pages.json');

function walk(dir) {
    return readdirSync(dir).flatMap((entry) => {
        const path = join(dir, entry);
        return statSync(path).isDirectory() ? walk(path) : [path];
    });
}

/**
 * The props a single-file component declares.
 *
 * Read out of the compiler's own binding metadata rather than by pattern
 * matching on the source, so a `defineProps` spread across lines, given types,
 * or written as an array still reports what Vue will actually accept.
 *
 * "Required" means the component declared it so. It is a weaker statement than
 * "the screen is broken without it" -- most pages default rather than require,
 * and a defaulted prop can still be the whole content of the page -- but it is
 * the only part of that the component states outright.
 */
function propsOf(path, name) {
    const { descriptor, errors } = parse(readFileSync(path, 'utf8'), { filename: path });

    if (errors.length) {
        throw new Error(`${name}: ${errors[0].message}`);
    }

    if (!descriptor.script && !descriptor.scriptSetup) {
        return { props: [], required: [] };
    }

    // id is only used to key the compiler's cache; it never reaches the output.
    const compiled = compileScript(descriptor, { id: name });

    // The compiler says what each binding is. Reading it from there rather than
    // matching on the source means a defineProps spread across lines, given
    // types, or written as an array still reports what Vue will accept.
    const props = Object.keys(compiled.bindings ?? {})
        .filter((key) => compiled.bindings[key] === 'props')
        .sort();

    // Which of them are required the compiler does not say, and the distinction
    // is worth publishing: it is the difference between a backend that has to
    // send something and one that may.
    const source = descriptor.scriptSetup?.content ?? descriptor.script?.content ?? '';
    const required = props.filter((prop) => {
        const declaration = new RegExp(`\\b${prop}\\s*:\\s*\\{([^{}]|\\{[^{}]*\\})*\\}`).exec(source);

        return declaration ? /required\s*:\s*true/.test(declaration[0]) : false;
    });

    return { props, required };
}

const files = walk(pagesDir).filter((path) => path.endsWith('.vue'));

const pages = [];
const props = {};

for (const path of files) {
    const name = `Escalated/${relative(pagesDir, path).slice(0, -4).split(sep).join('/')}`;

    pages.push(name);
    props[name] = propsOf(path, name);
}

pages.sort();

const { version } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const manifest = {
    $comment:
        'Generated by scripts/generate-page-manifest.js from src/pages. Every name here resolves to a component; a name a backend renders that is not here is a blank screen. `props` is what each component reads -- a backend sending something else renders the screen with no content in it.',
    version,
    pages,
    props: Object.fromEntries(pages.map((name) => [name, props[name]])),
};

const serialised = `${JSON.stringify(manifest, null, 4)}\n`;
const existing = (() => {
    try {
        return readFileSync(output, 'utf8');
    } catch {
        return null;
    }
})();

// --check is how CI asks whether the committed file still matches the pages on
// disk, without writing anything.
if (process.argv.includes('--check')) {
    if (existing !== serialised) {
        console.error('pages.json is out of date. Run: npm run pages:manifest');
        process.exit(1);
    }

    console.log(`pages.json is current (${pages.length} pages)`);
    process.exit(0);
}

writeFileSync(output, serialised);
console.log(`wrote pages.json (${pages.length} pages)`);
